const { PutObjectCommand, GetObjectCommand } = require("@aws-sdk/client-s3");
const { getSignedUrl } = require("@aws-sdk/s3-request-presigner");
const { v4: uuidv4 } = require("uuid");
const axios = require("axios");
const s3Client = require("../../awsConfig/s3");
const logger = require("../../utils/logger");

class S3MediaService {
  constructor() {
    this.bucket = process.env.AWS_BUCKET_NAME;
    this.region = process.env.AWS_REGION || "eu-north-1";
  }

  /**
   * Generates a presigned PUT URL allowing the client to upload private media directly to S3.
   * Key pattern: users/{userId}/ai-inputs/{uuid}-{fileName}
   */
  async createPresignedUploadUrl({ userId, fileName, fileType, expiresIn = 900 }) {
    if (!this.bucket) {
      throw new Error("AWS_BUCKET_NAME is not configured.");
    }

    const cleanFileName = (fileName || "upload.bin")
      .replace(/[^a-zA-Z0-9._-]/g, "_");
    const fileKey = `users/${userId}/ai-inputs/${uuidv4()}-${cleanFileName}`;

    const command = new PutObjectCommand({
      Bucket: this.bucket,
      Key: fileKey,
      ContentType: fileType || "application/octet-stream",
    });

    const uploadUrl = await getSignedUrl(s3Client, command, { expiresIn });

    return {
      uploadUrl,
      fileKey,
      expiresIn,
    };
  }

  /**
   * Directly uploads a Buffer or Base64 media to S3.
   */
  async uploadBuffer({ buffer, fileKey, contentType }) {
    if (!this.bucket) {
      throw new Error("AWS_BUCKET_NAME is not configured.");
    }

    const command = new PutObjectCommand({
      Bucket: this.bucket,
      Key: fileKey,
      Body: buffer,
      ContentType: contentType || "application/octet-stream",
    });

    await s3Client.send(command);

    const s3Url = `https://${this.bucket}.s3.${this.region}.amazonaws.com/${fileKey}`;
    return {
      fileKey,
      s3Url,
    };
  }

  /**
   * Direct upload from Base64 data string.
   */
  async uploadBase64({ userId, fileName, fileType, base64Data }) {
    const cleanFileName = (fileName || "upload.bin").replace(/[^a-zA-Z0-9._-]/g, "_");
    const fileKey = `users/${userId}/ai-inputs/${uuidv4()}-${cleanFileName}`;

    // Strip data prefix if present (e.g., data:image/png;base64,...)
    const base64Clean = base64Data.replace(/^data:[^;]+;base64,/, "");
    const buffer = Buffer.from(base64Clean, "base64");

    const result = await this.uploadBuffer({
      buffer,
      fileKey,
      contentType: fileType || "application/octet-stream",
    });

    const presignedReadUrl = await this.createPresignedReadUrl({ fileKey, expiresIn: 3600 });

    return {
      fileKey: result.fileKey,
      s3Url: result.s3Url,
      presignedReadUrl,
    };
  }

  /**
   * Generates a temporary presigned GET URL for Magica or users to access private S3 media.
   */
  async createPresignedReadUrl({ fileKey, expiresIn = 3600 }) {
    if (!this.bucket) {
      throw new Error("AWS_BUCKET_NAME is not configured.");
    }

    if (!fileKey) return null;

    // If it's already an external HTTPS URL and not S3 key, return as-is
    if (fileKey.startsWith("http://") || fileKey.startsWith("https://")) {
      return fileKey;
    }

    const command = new GetObjectCommand({
      Bucket: this.bucket,
      Key: fileKey,
    });

    try {
      const readUrl = await getSignedUrl(s3Client, command, { expiresIn });
      return readUrl;
    } catch (error) {
      logger.error(`Failed to generate presigned GET URL for ${fileKey}: ${error.message}`);
      throw error;
    }
  }

  /**
   * Downloads media generated by Magica (from temporary CDN URL) and securely saves it to AWS S3.
   * Path: users/{userId}/ai-outputs/{generationId}.{ext}
   */
  async downloadAndSaveToS3({ sourceUrl, userId, generationId, type }) {
    if (!sourceUrl) return null;

    try {
      logger.info(`Downloading AI generated ${type} from Magica: ${sourceUrl}`);
      const response = await axios.get(sourceUrl, {
        responseType: "arraybuffer",
        timeout: 60000,
      });

      const buffer = Buffer.from(response.data);
      const isVideo = type === "VIDEO" || type === "VIDEO_EDIT" || sourceUrl.endsWith(".mp4");
      const ext = isVideo ? "mp4" : "png";
      const contentType = isVideo ? "video/mp4" : "image/png";

      const fileKey = `users/${userId}/ai-outputs/${generationId}_${Date.now()}.${ext}`;

      const { s3Url } = await this.uploadBuffer({
        buffer,
        fileKey,
        contentType,
      });

      const presignedReadUrl = await this.createPresignedReadUrl({
        fileKey,
        expiresIn: 7 * 24 * 3600, // 7 days presigned URL
      });

      logger.info(`Saved AI output to S3: ${fileKey}`);

      return {
        s3Key: fileKey,
        s3Url,
        presignedReadUrl,
      };
    } catch (err) {
      logger.error(`Failed to download and upload AI output to S3: ${err.message}`);
      // Fallback to original URL if S3 upload failed so user isn't left empty handed
      return {
        s3Key: null,
        s3Url: sourceUrl,
        presignedReadUrl: sourceUrl,
      };
    }
  }
}

module.exports = new S3MediaService();
